friends = 0 
friends = friends + 1
print(friends) #2

# Augumented assignment operator
friends += 2
print(friends) #2

friends -= 1
print(friends) #2

friends *= 3
print(friends) #6

friends /= 2
print(friends) #3.0

friends **= 2
print(friends) #9.0

friends %= 2
print(friends) #1.0
